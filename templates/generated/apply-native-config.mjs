#!/usr/bin/env node
/**
 * Applies Web2App Studio configuration to the freshly generated Capacitor
 * native projects. Runs inside GitHub Actions, never on the web server.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const target = process.argv[2];
const config = JSON.parse(readFileSync("web2app.config.json", "utf8"));
const features = config.features ?? {};
const colors = config.colors ?? {};

function fail(message) {
  console.error(`::error::${message}`);
  process.exit(1);
}

function escapeXml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function addPlistEntry(plist, key, value) {
  if (plist.includes(`<key>${key}</key>`)) return plist;
  return plist.replace(
    /<\/dict>\s*<\/plist>\s*$/,
    `\t<key>${escapeXml(key)}</key>\n\t<string>${escapeXml(value)}</string>\n</dict>\n</plist>\n`
  );
}

function addPlistRaw(plist, key, rawXml) {
  if (plist.includes(`<key>${key}</key>`)) return plist;
  return plist.replace(
    /<\/dict>\s*<\/plist>\s*$/,
    `\t<key>${key}</key>\n${rawXml}\n</dict>\n</plist>\n`
  );
}

function applyAndroid() {
  const manifestPath = "android/app/src/main/AndroidManifest.xml";
  if (!existsSync(manifestPath)) {
    fail("AndroidManifest.xml was not generated by Capacitor.");
  }

  let manifest = readFileSync(manifestPath, "utf8");

  const permissions = new Set(["android.permission.INTERNET"]);

  if (features.camera) permissions.add("android.permission.CAMERA");

  if (features.location) {
    permissions.add("android.permission.ACCESS_COARSE_LOCATION");
    permissions.add("android.permission.ACCESS_FINE_LOCATION");
  }

  if (features.pushNotifications) {
    permissions.add("android.permission.POST_NOTIFICATIONS");
  }

  if (features.biometric) {
    permissions.add("android.permission.USE_BIOMETRIC");
  }

  const permissionXml = [...permissions]
    .filter((permission) =>
      !manifest.includes(`android:name="${permission}"`)
    )
    .map((permission) =>
      `    <uses-permission android:name="${permission}" />`
    )
    .join("\n");

  if (permissionXml) {
    manifest = manifest.replace(
      /(\s*)<application\b/,
      `\n${permissionXml}\n$1<application`
    );
  }

  if (features.deepLinks) {
    const filters = [];

    if (config.deepLink?.host) {
      const host = escapeXml(config.deepLink.host);
      const prefix = config.deepLink.pathPrefix
        ? `\n            android:pathPrefix="${escapeXml(config.deepLink.pathPrefix)}"`
        : "";

      filters.push(`        <intent-filter android:autoVerify="true">
            <action android:name="android.intent.action.VIEW" />
            <category android:name="android.intent.category.DEFAULT" />
            <category android:name="android.intent.category.BROWSABLE" />
            <data android:scheme="https" android:host="${host}"${prefix} />
        </intent-filter>`);
    }

    if (config.deepLink?.scheme) {
      filters.push(`        <intent-filter>
            <action android:name="android.intent.action.VIEW" />
            <category android:name="android.intent.category.DEFAULT" />
            <category android:name="android.intent.category.BROWSABLE" />
            <data android:scheme="${escapeXml(config.deepLink.scheme)}" />
        </intent-filter>`);
    }

    const filterXml = filters.join("\n");

    const activityPattern =
      /(<activity\b[^>]*android:name="\.MainActivity"[\s\S]*?)(<\/activity>)/;

    if (!activityPattern.test(manifest)) {
      fail(
        "Could not find MainActivity in AndroidManifest.xml to add deep-link filters."
      );
    }

    manifest = manifest.replace(
      activityPattern,
      `$1${filterXml}\n    $2`
    );
  }

  writeFileSync(manifestPath, manifest);

  // Gradle version metadata
  const gradlePath = "android/app/build.gradle";

  if (!existsSync(gradlePath)) {
    fail("android/app/build.gradle was not generated.");
  }

  let gradle = readFileSync(gradlePath, "utf8");

  gradle = gradle.replace(
    /versionCode\s+\d+/,
    `versionCode ${Number(config.versionCode)}`
  );

  gradle = gradle.replace(
    /versionName\s+["'][^"']*["']/,
    `versionName "${config.versionName}"`
  );

  writeFileSync(gradlePath, gradle);

  // Status/navigation bar colours and contrast
  const stylesPath = "android/app/src/main/res/values/styles.xml";

  if (
    existsSync(stylesPath) &&
    (colors.statusBar || colors.navigationBar)
  ) {
    let styles = readFileSync(stylesPath, "utf8");
    const items = [];

    if (colors.statusBar) {
      items.push(
        `        <item name="android:statusBarColor">${escapeXml(colors.statusBar)}</item>`
      );

      items.push(
        `        <item name="android:navigationBarColor">${escapeXml(colors.navigationBar ?? colors.statusBar)}</item>`
      );
    }

    if (config.theme === "light") {
      items.push(
        '        <item name="android:windowLightStatusBar">true</item>'
      );
      items.push(
        '        <item name="android:windowLightNavigationBar">true</item>'
      );
    } else if (config.theme === "dark") {
      items.push(
        '        <item name="android:windowLightStatusBar">false</item>'
      );
      items.push(
        '        <item name="android:windowLightNavigationBar">false</item>'
      );
    }

    const pattern =
      /(<style name="AppTheme\.NoActionBar"[^>]*>)([\s\S]*?)(<\/style>)/;

    if (pattern.test(styles)) {
      styles = styles.replace(
        pattern,
        `$1$2\n${items.join("\n")}\n    $3`
      );

      writeFileSync(stylesPath, styles);
    } else {
      console.warn(
        "AppTheme.NoActionBar not found; skipping status bar colours."
      );
    }
  }

  if (config.websiteUrl.startsWith("http://")) {
    console.warn(
      "::warning::HTTP websites are blocked by Android/iOS release builds. Use HTTPS."
    );
  }
}

function applyIos() {
  const plistPath = "ios/App/App/Info.plist";

  if (!existsSync(plistPath)) {
    fail("Info.plist was not generated by Capacitor.");
  }

  let plist = readFileSync(plistPath, "utf8");
  const appName = config.appName;

  if (features.camera || features.gallery) {
    plist = addPlistEntry(
      plist,
      "NSCameraUsageDescription",
      `Allow ${appName} to take photos.`
    );

    plist = addPlistEntry(
      plist,
      "NSPhotoLibraryUsageDescription",
      `Allow ${appName} to access your photo library.`
    );

    plist = addPlistEntry(
      plist,
      "NSPhotoLibraryAddUsageDescription",
      `Allow ${appName} to save photos to your library.`
    );
  }

  if (features.location) {
    plist = addPlistEntry(
      plist,
      "NSLocationWhenInUseUsageDescription",
      `Allow ${appName} to use your location while the app is open.`
    );
  }

  if (features.biometric) {
    plist = addPlistEntry(
      plist,
      "NSFaceIDUsageDescription",
      `Use Face ID to unlock ${appName}.`
    );
  }

  if (features.deepLinks && config.deepLink?.scheme) {
    const scheme = escapeXml(config.deepLink.scheme);

    plist = addPlistRaw(
      plist,
      "CFBundleURLTypes",
      `\t<array>
\t\t<dict>
\t\t\t<key>CFBundleURLName</key>
\t\t\t<string>${escapeXml(config.packageId)}</string>
\t\t\t<key>CFBundleURLSchemes</key>
\t\t\t<array>
\t\t\t\t<string>${scheme}</string>
\t\t\t</array>
\t\t</dict>
\t</array>`
    );
  }

  if (
    features.deepLinks &&
    config.deepLink?.host &&
    !config.deepLink?.scheme
  ) {
    console.warn(
      "::warning::Universal links (https deep links) require an Associated Domains entitlement and an Apple developer team. Configure it in Xcode after downloading an iOS build."
    );
  }

  writeFileSync(plistPath, plist);

  const pbxPath = "ios/App/App.xcodeproj/project.pbxproj";

  if (existsSync(pbxPath)) {
    let pbx = readFileSync(pbxPath, "utf8");

    pbx = pbx.replace(
      /MARKETING_VERSION = [^;]+;/g,
      `MARKETING_VERSION = ${config.versionName};`
    );

    pbx = pbx.replace(
      /CURRENT_PROJECT_VERSION = [^;]+;/g,
      `CURRENT_PROJECT_VERSION = ${Number(config.versionCode)};`
    );

    writeFileSync(pbxPath, pbx);
  }
}

if (target === "android") {
  applyAndroid();
} else if (target === "ios") {
  applyIos();
} else {
  fail("Usage: node scripts/apply-native-config.mjs <android|ios>");
}

console.log(`Applied Web2App configuration for ${target}.`);
