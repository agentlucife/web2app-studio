const TEMPLATE_DIR = path.join(process.cwd(), "templates", "generated");

const CAPACITOR_VERSION = "8.6.2";

async function template(name: string) {
  return readFile(path.join(TEMPLATE_DIR, name), "utf8");
}

function packageJson(config: AppConfig) {
  const dependencies: Record<string, string> = {
    "@capacitor/core": CAPACITOR_VERSION,
    "@capacitor/android": CAPACITOR_VERSION,
    "@capacitor/ios": CAPACITOR_VERSION,
    "@capacitor/app": "8.1.2",
    "@capacitor/splash-screen": "8.0.2",
  };
  if (config.features.statusBar) dependencies["@capacitor/status-bar"] = "8.0.4";
  if (config.features.camera || config.features.gallery) dependencies["@capacitor/camera"] = "8.2.6";
  if (config.features.location) dependencies["@capacitor/geolocation"] = "8.2.4";
  if (config.features.pushNotifications) dependencies["@capacitor/push-notifications"] = "8.1.3";
  if (config.features.share) dependencies["@capacitor/share"] = "8.0.3";
  if (config.features.fileDownloads || config.features.fileUploads) {
    dependencies["@capacitor/filesystem"] = "8.1.5";
  }
  if (config.features.biometric) {
    dependencies["@aparajita/capacitor-biometric-auth"] = "10.0.0";
  }
  return JSON.stringify(
    {
      name: `web2app-${sanitizeStorageFilename(config.packageId.replace(/\./g, "-"))}`,
      version: config.versionName,
      private: true,
      description: config.description || `${config.appName} — generated by Web2App Studio`,
      scripts: {
        sync: "cap sync",
        "add:android": "cap add android",
        "add:ios": "cap add ios",
        "open:android": "cap open android",
        "open:ios": "cap open ios",
      },
      dependencies,
      devDependencies: {
        "@capacitor/assets": "4.0.0",
        "@capacitor/cli": CAPACITOR_VERSION,
        typescript: "^5.9.0",
      },
    },
    null,
    2
  );
}

function capacitorConfig(config: AppConfig) {
  const hostname = new URL(config.websiteUrl).hostname;
  const allowNavigation = Array.from(
    new Set([hostname, ...(config.navigation.allowNavigation ?? [])])
  );
  const statusBarStyle =
    config.theme === "light" ? "DARK" : config.theme === "dark" ? "LIGHT" : "DEFAULT";

  return JSON.stringify(
    {
      appId: config.packageId,
      appName: config.appName,
      webDir: "www",
      loggingBehavior: "none",
      server: {
        url: config.websiteUrl,
        hostname,
        androidScheme: "https",
        iosScheme: "https",
        allowNavigation,
        ...(config.features.offlinePage ? { errorPath: "offline.html" } : {}),
      },
      android: {
        allowMixedContent: false,
        captureInput: true,
        webContentsDebuggingEnabled: false,
        backgroundColor: config.colors.splashBackground,
      },
      ios: {
        contentInset: "always",
        backgroundColor: config.colors.splashBackground,
        scrollEnabled: true,
        limitsNavigationsToAppBoundDomains: false,
      },
      plugins: {
        SplashScreen: {
          launchShowDuration: 1200,
          launchAutoHide: true,
          backgroundColor: config.colors.splashBackground,
          androidScaleType: "CENTER_CROP",
          showSpinner: false,
          splashFullScreen: true,
          splashImmersive: true,
        },
        ...(config.features.statusBar
          ? {
              StatusBar: {
                style: statusBarStyle,
                backgroundColor: config.colors.statusBar,
                overlaysWebView: false,
              },
            }
          : {}),
        ...(config.features.pushNotifications
          ? {
              PushNotifications: {
                presentationOptions: ["badge", "sound", "alert"],
              },
            }
          : {}),
      },
    },
    null,
    2
  );
}

function web2appConfig(config: AppConfig) {
  return JSON.stringify(
    {
      generator: "web2app-studio",
      generatedAt: new Date().toISOString(),
      appName: config.appName,
      packageId: config.packageId,
      websiteUrl: config.websiteUrl,
      versionName: config.versionName,
      versionCode: config.versionCode,
      minSdk: 24,
      theme: config.theme,
      colors: config.colors,
      navigation: config.navigation,
      features: config.features,
      deepLink: config.deepLink,
    },
    null,
    2
  );
}

