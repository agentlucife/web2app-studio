async function fetchAsset(
  storagePath: string | undefined,
  userId: string | undefined,
  kind: "icon" | "splash",
  config: AppConfig
): Promise<Buffer> {
  if (storagePath && userId) {
    try {
      assertOwnedUploadPath(userId, storagePath);
      return await downloadObject(UPLOADS_BUCKET, storagePath);
    } catch {
      // Fall through to a generated placeholder.
    }
  }
  return generatedAsset(kind, config);
}

async function generatedAsset(kind: "icon" | "splash", config: AppConfig) {
  const primary = config.colors.primary;
  const background = config.colors.splashBackground;
  const initial = config.appName.trim().charAt(0).toUpperCase() || "A";
  if (kind === "icon") {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024">
      <defs>
        <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
          <stop offset="0%" stop-color="${primary}"/>
          <stop offset="100%" stop-color="#047857"/>
        </linearGradient>
      </defs>
      <rect width="1024" height="1024" rx="224" fill="url(#g)"/>
      <text x="512" y="675" font-family="Arial, Helvetica, sans-serif" font-size="460"
        font-weight="700" fill="#04110c" text-anchor="middle">${initial.replace(/[<>&]/g, "")}</text>
    </svg>`;
    return sharp(Buffer.from(svg)).png().toBuffer();
  }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="2732" height="2732">
    <rect width="2732" height="2732" fill="${background}"/>
    <rect x="1106" y="1106" width="520" height="520" rx="120" fill="${primary}"/>
    <text x="1366" y="1465" font-family="Arial, Helvetica, sans-serif" font-size="250"
      font-weight="700" fill="#04110c" text-anchor="middle">${initial.replace(/[<>&]/g, "")}</text>
  </svg>`;
  return sharp(Buffer.from(svg)).png().toBuffer();
}

export type GeneratedProject = {
  files: FileToPush[];
  zip: Buffer;
  commitMessage: string;
  appConfig: AppConfig;
};

export async function generateCapacitorProject(
  config: AppConfig,
  options: { userId?: string; buildId?: string; commitMarker?: string } = {}
): Promise<GeneratedProject> {
  const icon = await fetchAsset(config.assets.iconPath, options.userId, "icon", config);
  const splash = await fetchAsset(config.assets.splashPath, options.userId, "splash", config);

  const [androidWorkflow, iosWorkflow, applyScript, notifyScript, offlineHtml, indexHtml] =
    await Promise.all([
      template("android-workflow.yml"),
      template("ios-workflow.yml"),
      template("apply-native-config.mjs"),
      template("notify-build.mjs"),
      template("offline.html"),
      template("index.html"),
    ]);

  const files: FileToPush[] = [
    { path: "package.json", content: packageJson(config) },
    { path: "capacitor.config.json", content: capacitorConfig(config) },
    { path: "web2app.config.json", content: web2appConfig(config) },
    { path: "README-GENERATED.md", content: readme(config) },
    { path: ".gitignore", content: gitignore() },
    { path: "www/index.html", content: indexHtml },
    { path: "www/offline.html", content: offlineHtml },
    { path: "assets/icon.png", content: icon },
    { path: "assets/splash.png", content: splash },
    { path: "scripts/apply-native-config.mjs", content: applyScript },
    { path: "scripts/notify-build.mjs", content: notifyScript },
    { path: ".github/workflows/android.yml", content: androidWorkflow },
    { path: ".github/workflows/ios.yml", content: iosWorkflow },
  ];

  const zip = new JSZip();
  for (const file of files) {
    zip.file(file.path, file.content);
  }
  const zipBuffer = await zip.generateAsync({
    type: "nodebuffer",
    compression: "DEFLATE",
    compressionOptions: { level: 6 },
  });

  return {
    files,
    zip: zipBuffer,
    commitMessage: `Web2App Studio build${options.commitMarker ? ` ${options.commitMarker}` : ""}`,
    appConfig: config,
  };
}

